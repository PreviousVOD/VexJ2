package j2.board.wukong

import spinal.core._

final class XilinxBufg extends BlackBox {
  val I = in Bool ()
  val O = out Bool ()
  setDefinitionName("BUFG")
}

final class WukongPll extends BlackBox {
  val CLKIN1, CLKFBIN, PWRDWN, RST = in Bool ()
  val CLKOUT0, CLKFBOUT, LOCKED    = out Bool ()
  setDefinitionName("PLLE2_BASE")
  addGeneric("CLKIN1_PERIOD", 20.0)
  addGeneric("DIVCLK_DIVIDE", 1)
  addGeneric("CLKFBOUT_MULT", 16)
  addGeneric("CLKOUT0_DIVIDE", 25)
  addGeneric("STARTUP_WAIT", "FALSE")
}

final class XilinxIoBuffer extends BlackBox {
  val I, T = in Bool ()
  val O    = out Bool ()
  val IO   = inout(Analog(Bool()))
  setDefinitionName("IOBUF")
}

final class XilinxStartup extends BlackBox {
  val CLK, GSR, GTS, KEYCLEARB, PACK           = in Bool ()
  val USRCCLKO, USRCCLKTS, USRDONEO, USRDONETS = in Bool ()
  val EOS                                      = out Bool ()
  setDefinitionName("STARTUPE2")
  addGeneric("PROG_USR", "FALSE")
}

/** Generated by Vivado from proc_sys_reset v5.0, with active-high reset inputs. */
final class XilinxSystemReset extends BlackBox {
  val slowest_sync_clk, ext_reset_in, aux_reset_in, mb_debug_sys_rst, dcm_locked = in Bool ()
  val peripheral_reset                                                           = out Bits (1 bits)
  setDefinitionName("wukong_reset")
}
